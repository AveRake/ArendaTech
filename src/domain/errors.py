## @brief Базовое исключение предметной области
class DomainError(Exception):
    """Базовая ошибка бизнес-логики сервиса аренды."""


## @brief Нарушены входные данные (даты, единицы техники, состояние)
class ValidationError(DomainError):
    """Ошибка валидации входных данных."""


## @brief Недостаточно прав для выполнения операции
class PermissionDenied(DomainError):
    """Пользователь не является сотрудником сервиса."""


## @brief Недопустимый переход статуса заявки
class InvalidTransition(DomainError):
    """Переход между статусами заявки запрещён."""


## @brief Объект не найден в хранилище
class NotFoundError(DomainError):
    """Запрошенный объект отсутствует."""
