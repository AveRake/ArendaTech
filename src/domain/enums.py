#  литералах.

from enum import Enum


## @brief Роль пользователя в системе
class UserRole(Enum):
    ## @brief Студент
    STUDENT = "студент"
    ## @brief Преподаватель
    TEACHER = "преподаватель"
    ## @brief Администратор (сотрудник, оформляющий заявки)
    ADMINISTRATOR = "администратор"
    ## @brief Техник (сотрудник, выдающий и принимающий технику)
    TECHNICIAN = "техник"


## @brief Статус заявки на аренду
class RequestStatus(Enum):
    ## @brief Заявка создана и ожидает решения
    PENDING = "На рассмотрении"
    ## @brief Заявка одобрена сотрудником
    APPROVED = "Одобрена"
    ## @brief Заявка отклонена сотрудником
    REJECTED = "Отклонена"
    ## @brief Техника выдана по заявке
    ISSUED = "Выдана"
    ## @brief Аренда завершена, техника возвращена
    CLOSED = "Закрыта"


## @brief Состояние единицы техники
class UnitStatus(Enum):
    ## @brief Единица свободна и может быть выдана
    AVAILABLE = "Доступна"
    ## @brief Единица выдана по заявке
    ISSUED = "Выдана"
    ## @brief Единица на ремонте после возврата
    IN_REPAIR = "На ремонте"
    ## @brief Единица списана (утеря)
    WRITTEN_OFF = "Списана"


## @brief Результат осмотра техники при возврате
class ReturnCondition(Enum):
    ## @brief Техника возвращена в исправном состоянии
    GOOD = "Хорошее"
    ## @brief Техника повреждена
    DAMAGED = "Повреждено"
    ## @brief Техника утеряна
    LOST = "Утеряно"


## @brief Причина начисления штрафа
class FineReason(Enum):
    ## @brief Просрочка возврата
    OVERDUE = "Просрочка"
    ## @brief Повреждение техники
    DAMAGE = "Повреждение"
    ## @brief Утеря техники
    LOSS = "Утеря"
